                <h2 class="font-bold pt-4">
                    Conduct as a Professional Handler
                </h2>
                <p>
                    Showcasing a dog’s attributes in various events organized or
                    participated in by PCCI has always involved human
                    involvement. An individual who handles participating dogs
                    and who receives financial compensation for doing so is
                    known as a Professional Handler.
                </p>
                <p>
                    The Professional Handler, performs the role of the Exhibitor
                    in showing the dog but for a fee. He therefore must, in
                    addition to meeting the minimum acceptable behavior required
                    of an Exhibitor, also ensure that he shall conduct himself
                    according to the additional guidelines stated below:
                </p>
                <ol class="list-decimal list-outside pl-8 space-y-4">
                    <li>
                        A Professional Handler must ensure that the welfare of
                        the dogs in his care is a priority, not only at dog
                        shows but at home and on the road. He shall place their
                        well-being, security, and safety above all other
                        business considerations. He has ultimate responsibility
                        for the dogs under his care.
                    </li>
                    <li>
                        A Professional Handler shall conduct himself in a
                        sportsmanlike manner at all times in his relationships
                        with fellow handlers, assistants, exhibitors, judges and
                        clients, which includes courteous verbal interchanges
                        and a professional appearance.
                    </li>
                    <li>
                        A Professional Handler shall abide by all published PCCI
                        rules applying to registration and dog shows.
                    </li>
                    <li>
                        A Professional Handler shall conduct his business
                        relationships with clients in a fair and honest manner,
                        based on a pre-announced and mutually agreed upon rate
                        schedule and handler/client agreement.
                    </li>
                    <li>
                        A Professional Handler shall provide his clients with
                        their ribbons, trophies and information about their
                        dogs’ placements at each show in a timely manner.
                    </li>
                    <li>
                        A Professional Handler shall provide his clients with
                        itemized monthly billing statements, if applicable.
                    </li>
                    <li>
                        A Professional Handler shall ensure that his clients
                        thoroughly understand payment and release terms.
                    </li>
                    <li>
                        A Professional Handler shall confirm with any previous
                        handler of a new or prospective client that a valid
                        outstanding balance does not exist, and will not handle
                        any dogs for a client with a valid outstanding balance
                        with a previous professional handler.
                    </li>
                </ol>

                <h2 class="font-bold pt-4">Conduct as a Judge</h2>
                <p>
                    Dog events, being mostly competitive in character require
                    the application of a judging procedure to determine how each
                    competitor eventually gets ranked or how a participant meets
                    a prescribed standard of performance. In both situations,
                    the presence of an individual(s) who has been sufficiently
                    trained to apply the appropriate judging procedure and
                    assess the degree to which the standards are being met
                    becomes a necessity. Thus, the need for the Judge who must
                    be knowledgeable about the task at hand, who has the
                    appropriate skills to carry out the job given the social and
                    environmental pressures, and most of all, the integrity and
                    the credibility to dispense fair and honest judgement over
                    the competitors or participants.
                </p>
                <p>
                    A judge must ensure that his behavior in dog-related events
                    or situations shall not cast a shadow of doubt on his
                    ability to dispense fair, rational and objective judgement
                    and should be mindful to always create a level playing field
                    for the competitors in the event where he is adjudicating.
                </p>
                <ol class="list-decimal list-outside pl-8 space-y-4">
                    <li>
                        A Judge shall act with professional decorum at all
                        times.
                    </li>
                    <li>
                        A Judge shall give every exhibit and exhibitor fair and
                        equal opportunity in each and every class.
                    </li>
                    <li>
                        A Judge shall act in a polite manner while carrying out
                        each judging assignment.
                    </li>
                    <li>
                        A Judge shall present himself in attire that satisfies
                        the dress code prescribed by the PCCI Judging Committee.
                        Such attire must also be acceptable, appropriate and
                        comfortable for each judging assignment.
                    </li>
                    <li>
                        A Judge shall punctually report to the show chairman to
                        fulfil his judging assignment.
                    </li>
                    <li>
                        A Judge must excuse from the competition an exhibit
                        which, at any time during the judging procedure, shows
                        an obvious physical impediment or qualities that are
                        considered disqualification in the exhibit’s breed
                        standard, cannot be handled or may be regarded as
                        vicious.
                    </li>
                    <li>
                        A Judge shall not enter or exhibit any dog at any
                        Conformation Show if said show is being held with
                        another show at which he is appointed to judge, if the
                        former is being held on the same weekend, at the same
                        venue, by the same organizing club or where the entries
                        for both shows are printed on a single catalog.
                    </li>
                    <li>
                        A Judge shall excuse from competition any exhibitor (and
                        his exhibit), who offers information to the Judge that
                        may be regarded as designed to influence the latter’s
                        decision. He should report the incident to the Chairman
                        of the PCCI Show Committee.
                    </li>
                    <li>
                        A Judge shall report to the Chairman of the PCCI Show
                        Committee if he is approached to favor or disfavor a
                        particular exhibit.
                    </li>
                    <li>
                        A Judge shall report the matter in writing to the
                        Chairman of the PCCI Show Committee if he is approached
                        with an inducement and/or bribe to advantage or
                        disadvantage an exhibit.
                    </li>
                    <li>
                        A Judge shall not smoke, drink alcohol or use his mobile
                        phone to make or receive calls while inside the ring.
                    </li>
                    <li>
                        A Judge shall not criticize by act or word the work of
                        other judges, nor offer criticism of any previously
                        judged dog(s) to anyone including other officiating
                        judges during the course of the show, except for
                        authorized ringside mentoring.
                    </li>
                    <li>
                        A Judge shall judge exhibits in accordance with their
                        relevant breed standard.
                    </li>
                    <li>
                        A Judge shall not read the show catalogue of the show he
                        is judging before he has finished judging all his
                        assigned classes for that show.
                    </li>
                    <li>A Judge shall not solicit judging assignments.</li>
                </ol>
