                <p>
                    Being first and foremost a purebred dog Registry, the PCCI
                    recognizes the key role that its members who breed dogs play
                    in the promotion of the love for purebred dogs. The Registry
                    was created to serve the Breeders who in turn, must exercise
                    diligence, self-discipline and honesty to help ensure the
                    Registry’s integrity. The Breeders are likewise expected to
                    exhibit responsibility for their breeding efforts as well as
                    ensure that they treat their breeding dogs and puppies
                    humanely at all times.
                </p>
                <ol class="list-decimal list-outside pl-8 space-y-4">
                    <li>
                        A Breeder shall make every effort to learn about the
                        structure, anatomy, action, inherited traits and
                        behavior of the dog, especially where such learning
                        applies to his chosen breed or breeds.
                    </li>
                    <li>
                        A Breeder shall educate himself to recognize the correct
                        conformation of his chosen breed or breeds,
                        familiarizing himself with the PCCI breed standard and
                        representative dogs, prior to breeding a stud dog or a
                        brood bitch.
                    </li>
                    <li>
                        A Breeder shall at all times breed for the improvement
                        of the breed as exemplified by the PCCI breed standard.
                    </li>
                    <li>
                        A Breeder breeds only animals that are in good health
                        and which are physically and temperamentally sound.
                    </li>
                    <li>
                        A Breeder strives to produce puppies of such quality
                        that they will serve to improve and complement the breed
                        and, in good faith, avoid breeding individuals known to
                        have, or are strongly suspected of having, a serious
                        inherited disease or defect that will likely be passed
                        on to offspring and that, if inherited, would
                        significantly affect the quality of life of any
                        offspring that would be produced.
                    </li>
                    <li>
                        A Breeder must represent each puppy sold as accurately
                        as possible.
                    </li>
                    <li>
                        A Breeder must be willing to act as a mentor to persons
                        with whom they place puppies and encourage an open
                        dialog for the life of the dog.
                    </li>
                </ol>

                <h2 class="font-bold pt-4">Conduct as an Exhibitor</h2>
                <p>
                    The PCCI organizes various events that showcase outstanding
                    purebred dog characteristics to promote greater awareness
                    among its breeder members. It also stages or participates in
                    other events that exhibit other valuable canine
                    characteristics to heighten their appreciation and increase
                    overall public awareness, with the ultimate goal of
                    broadening the love for dogs. Members who participate in
                    such events are known as Exhibitors. Exhibitors may
                    personally handle or show their own dogs or opt to hire
                    professional handlers to do so.
                </p>
                <p>
                    An Exhibitor must show good sportsmanship and good will at
                    all dog-related events organized by the PCCI, its Affiliated
                    Clubs, or which it co-organized or participated in. Winning
                    and losing with grace is the minimum standard of good
                    sportsmanship and all forms of competition. Good
                    sportsmanship and general civility are consistent. The
                    Exhibitor must, during such events, display adherence to
                    fair play, honesty, courtesy, and vigorous competition,
                    whether inside or outside of the ring.
                </p>
                <ol class="list-decimal list-outside pl-8 space-y-4">
                    <li>
                        An Exhibitor shall primarily be concerned with the
                        health and welfare of his dogs in and out of the ring.
                        Further, he shall devote extra effort to make sure that
                        his exhibit’s health and welfare are looked after from
                        the time it leaves its residence to the time it goes
                        back. He shall ensure that the exhibit is safely
                        transported, has access to feed and/or water, as
                        appropriate, is not unduly exposed to situations,
                        persons or other exhibits that could cause it harm.
                    </li>
                    <li>
                        An Exhibitor shall respect and follow all rules on
                        Exhibiting and Showing as prescribed by the PCCI.
                    </li>
                    <li>
                        An Exhibitor shall always be courteous to fellow
                        Exhibitors, Professional Handlers and to the Judge (s).
                    </li>
                    <li>
                        An Exhibitor shall clean after his Exhibit and assist in
                        maintaining cleanliness and orderliness in the event
                        venue.
                    </li>
                    <li>
                        An Exhibitor shall observe proper decorum at all times
                        during an event. He shall wear the acceptable attire,
                        per PCCI guidelines, when inside the ring.
                    </li>
                    <li>An Exhibitor shall accept constructive criticism.</li>
                    <li>
                        An Exhibitor shall decline to enter or exhibit under a
                        judge where it might reasonably appear that the judge’s
                        placements could be based on something other than the
                        merits of the dogs.
                    </li>
                    <li>
                        An Exhibitor shall refuse to compromise the impartiality
                        of a judge. He shall,
